function qualityPreamble(taskName: string, country: string): string {
  return `[مهمة متخصصة موجّهة للمحامين والمختصين: ${taskName} — الدولة: ${country}]

القواعد المنهجية المُلزِمة:
• يُميَّز بين: الوقائع الثابتة بالمستندات / المدّعى بها / الافتراضات.
• يُميَّز بين: النص النافذ / المعدّل / الملغى / غير المتحقق منه.
• يُميَّز بين: القاعدة العامة / الاستثناء؛ وبين: الحق الموضوعي / إجراءات المطالبة به.
• يُميَّز بين: قوة المركز القانوني / إمكانية إثباته.
• لا تُفترض وقائع غير مذكورة — إن نقصت بيانات جوهرية أعرض قائمة بها وأصدر رأياً أولياً مشروطاً.
• لا تُذكر أرقام مواد أو أحكام أو تعاميم إلا إذا وردت حرفياً في المصادر المسترجعة.
• علامة [غير متحقق] تُوضع أمام أي معلومة لم تتحقق من مصدرها.
• يُفصل فصلاً تاماً بين: النص النظامي / التحليل / الاستنتاج.
• عند تعارض مصدرين: يُقدَّم الأحدث والأعلى قوة مع بيان التعارض.
• حظر مطلق غير قابل للتجاوز: يُمنع تقديم توقع لنتيجة دعوى أو وصف الموقف بـ"قوي/مرجّح/يُرجَّح" — يُبيَّن تأثير العوامل دون ترجيح نتيجة.

`;
}

